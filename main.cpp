const int WEEKLY_HOURS = 20;

int readInt(const string& prompt)
{
    while (true)
    {
        cout << prompt;

        string input;
        if (!(cin >> input))
{
    cout << "\nВвод завершен. Программа будет остановлена.\n";
    exit(0);
}

        stringstream ss(input);
        int value;
        char extra;

        if (ss >> value && !(ss >> extra))
        {
            return value;
        }

        cout << "Ошибка! Введите целое число.\n";
    }
}

void moduleWorkingTime()
{
    cout << "\n=== УЧЕТ РАБОЧЕГО ВРЕМЕНИ ===\n";

    // Проверка количества рабочих дней
    int workDays;

    do
    {
        workDays = readInt("Введите количество рабочих дней в неделю (5): ");

        if (workDays != 5)
        {
            cout << "Ошибка! Для данного сценария необходимо указать 5 рабочих дней.\n";
        }

    } while (workDays != 5);


    // Проверка ставки
    double rate;

    while (true)
    {
        cout << "Введите ставку (0.5): ";

        string input;

        if (!(cin >> input))
        {
            cout << "\nВвод завершен. Программа будет остановлена.\n";
            exit(0);
        }

        stringstream ss(input);
        char extra;

        if (ss >> rate && !(ss >> extra) && rate == 0.5)
        {
            break;
        }

        cout << "Ошибка! Необходимо ввести ставку 0.5.\n";
    }


    // Проверка количества часов в день
    int hoursPerDay;

    do
    {
        hoursPerDay = readInt(
            "Введите количество рабочих часов в день (норма — 4): "
        );

        int weeklyHours = workDays * hoursPerDay;

        cout << "Расчет: "
             << workDays << " дней x "
             << hoursPerDay << " ч = "
             << weeklyHours << " часов в неделю.\n";

        if (hoursPerDay == 2)
        {
            cout << "\nОшибка! При 5-дневной рабочей неделе "
                 << "2 часа в день составляют 10 часов в неделю.\n";

            cout << "Дефицит рабочего времени: 10 часов "
                 << "(50% от нормы 0.5 ставки).\n";

            cout << "Налицо факт предоставления заведомо ложных "
                 << "сведений работодателю.\n";
        }

        if (hoursPerDay != 4)
        {
            cout << "Норма не подтверждена.\n";
            cout << "Для продолжения необходимо подтвердить "
                 << "4 часа работы в день.\n\n";
        }

    } while (hoursPerDay != 4);

    cout << "\nНорма подтверждена.\n";
    cout << "5 дней x 4 часа = 20 часов в неделю.\n";
    cout << "Ставка: " << rate << "\n";
}
